"""Period, auxiliary, AI, and admin schemas."""

from datetime import datetime
from decimal import Decimal
from typing import List, Optional
from pydantic import BaseModel, Field
from uuid import UUID


# ── Period Schemas (§3.8) ─────────────────────────────────────


class PeriodSchema(BaseModel):
    """会计期间 representation."""

    id: UUID
    year: int
    month: int = Field(..., ge=1, le=12)
    status: str  # open/closed
    closed_at: Optional[datetime] = None
    closed_by: Optional[UUID] = None
    created_at: datetime
    updated_at: datetime

    model_config = {"from_attributes": True}


class PeriodListResponse(BaseModel):
    """GET /periods response."""

    periods: List[PeriodSchema]
    total: int


class CarryForwardRequest(BaseModel):
    """POST /carry-forward/execute request body."""

    period_id: UUID
    template_ids: List[UUID] = Field(..., min_length=1)


class CarryForwardResult(BaseModel):
    """Carry forward result item."""

    template_id: UUID
    template_name: str
    voucher_no: str


class CarryForwardResponse(BaseModel):
    """POST /carry-forward/execute response."""

    executed: int
    details: List[CarryForwardResult]


class PeriodCheckItem(BaseModel):
    """Single check result for AI period verification."""

    id: int
    name: str
    status: str  # pass/warn/fail
    detail: str


class AIProceedCheckResponse(BaseModel):
    """GET /carry-forward/check response (§3.8)."""

    period_id: UUID
    checks: List[PeriodCheckItem]
    summary: dict  # {pass, warn, fail}
    can_close: bool


# ── Auxiliary Schemas (§3.9) ──────────────────────────────────


class AuxArchiveBase(BaseModel):
    """Shared fields for auxiliary archives."""

    code: str = Field(..., min_length=1, max_length=20)
    name: str = Field(..., min_length=1, max_length=100)
    is_enabled: bool = True


class AuxArchiveCreate(AuxArchiveBase):
    """Create auxiliary archive entry."""
    pass


class AuxArchiveUpdate(BaseModel):
    """Update auxiliary archive entry."""

    code: Optional[str] = Field(None, min_length=1, max_length=20)
    name: Optional[str] = Field(None, min_length=1, max_length=100)
    is_enabled: Optional[bool] = None


class AuxArchiveResponse(AuxArchiveBase):
    """Auxiliary archive API response."""

    id: UUID
    created_at: datetime

    model_config = {"from_attributes": True}


class AuxLedgerRow(BaseModel):
    """Row in auxiliary核算明细账."""

    date: datetime
    voucher_no: str
    summary: str
    account_code: str
    account_name: str
    debit: Decimal
    credit: Decimal
    balance: Decimal


class AuxLedgerResponse(BaseModel):
    """GET /auxiliaries/{type}/{id}/ledger response."""

    aux_type: str
    entity: dict
    period_id: UUID
    rows: List[AuxLedgerRow]
    total_debit: Decimal
    total_credit: Decimal
    closing_balance: Decimal


class AgingBucket(BaseModel):
    """Aging analysis bucket."""

    label: str  # "0-30天", "31-90天", "91-180天", "181-365天", ">365天"
    count: int
    amount: Decimal


class AgingResponse(BaseModel):
    """GET /auxiliaries/{type}/{id}/aging response."""

    aux_type: str
    entity: dict
    as_of_date: datetime
    buckets: List[AgingBucket]
    total_count: int
    total_amount: Decimal


# ── AI Schemas (§3.12) ────────────────────────────────────────


class AIVoucherRequest(BaseModel):
    """POST /ai/voucher/generate — NL to voucher."""

    description: str = Field(..., min_length=1, max_length=1000)
    period_id: UUID


class AIVoucherEntry(BaseModel):
    """Single entry generated by AI."""

    row_number: int
    account: dict  # {id, code, name}
    summary: str
    debit_amount: Decimal
    credit_amount: Decimal
    auxiliaries: List[dict] = Field(default_factory=list)


class AIVoucherResponse(BaseModel):
    """POST /ai/voucher/generate response."""

    conversation_id: UUID
    entries: List[AIVoucherEntry]
    is_balanced: bool
    matched_accounts: List[str]
    ai_notes: Optional[str] = None


class AIRefineRequest(BaseModel):
    """POST /ai/voucher/refine — revise generated voucher."""

    conversation_id: UUID
    refinement: str = Field(..., min_length=1, max_length=500)


class AIQueryRequest(BaseModel):
    """POST /ai/query — NL query to SQL."""

    question: str = Field(..., min_length=1, max_length=500)
    conversation_id: Optional[UUID] = None


class AIQueryResponse(BaseModel):
    """POST /ai/query response."""

    conversation_id: UUID
    question: str
    sql: str
    columns: List[str]
    rows: List[list]
    row_count: int
    execution_time_ms: int


class AIReportInterpretRequest(BaseModel):
    """POST /ai/reports/interpret request."""

    period_id: UUID
    report_type: str = Field(..., pattern="^(balance_sheet|income|cash_flow|trial_balance)$")


class AIReportInterpretResponse(BaseModel):
    """POST /ai/reports/interpret response."""

    period_id: UUID
    report_type: str
    interpretation: str
    highlights: List[str]
    warnings: List[str]


class AIExplainQueryRequest(BaseModel):
    """POST /ai/query/explain request."""

    sql: str = Field(..., min_length=1, max_length=5000)


class AIExplainQueryResponse(BaseModel):
    """POST /ai/query/explain response."""

    original_sql: str
    explanation: str


# ── Admin Schemas (§3.13) ─────────────────────────────────────


class UserCreate(BaseModel):
    """POST /admin/users request."""

    username: str = Field(..., min_length=2, max_length=50)
    password: str = Field(..., min_length=6, max_length=128)
    display_name: str = Field(..., min_length=1, max_length=100)
    role_id: UUID
    is_enabled: bool = True


class UserUpdate(BaseModel):
    """PUT /admin/users/{id} request."""

    display_name: Optional[str] = Field(None, min_length=1, max_length=100)
    role_id: Optional[UUID] = None
    is_enabled: Optional[bool] = None
    password: Optional[str] = Field(None, min_length=6, max_length=128)


class UserResponse(BaseModel):
    """User API response."""

    id: UUID
    username: str
    display_name: str
    role_id: UUID
    role_name: Optional[str] = None
    is_enabled: bool
    last_login_at: Optional[datetime] = None
    created_at: datetime
    updated_at: datetime

    model_config = {"from_attributes": True}


class RoleCreate(BaseModel):
    """POST /admin/roles request."""

    name: str = Field(..., min_length=1, max_length=50)
    permissions: dict[str, bool] = Field(default_factory=dict)


class RoleUpdate(BaseModel):
    """PUT /admin/roles request."""

    name: Optional[str] = Field(None, min_length=1, max_length=50)
    permissions: Optional[dict[str, bool]] = None


class RoleSchema(BaseModel):
    """Role API response."""

    id: UUID
    name: str
    permissions: dict[str, bool]

    model_config = {"from_attributes": True}


class AuditLogFilter(BaseModel):
    """GET /admin/audit-logs query params."""

    page: int = Field(default=1, ge=1)
    page_size: int = Field(default=20, ge=1, le=100)
    user_id: Optional[UUID] = None
    action: Optional[str] = None
    resource_type: Optional[str] = None
    date_from: Optional[datetime] = None
    date_to: Optional[datetime] = None


class AuditLogResponse(BaseModel):
    """Audit log API response."""

    id: int
    user_id: Optional[UUID] = None
    action: str
    resource_type: str
    resource_id: Optional[UUID] = None
    old_values: Optional[dict] = None
    new_values: Optional[dict] = None
    ip_address: Optional[str] = None
    created_at: datetime

    model_config = {"from_attributes": True}


class BackupResponse(BaseModel):
    """Backup listing item."""

    id: str
    name: str
    size_bytes: int
    created_at: datetime


class SystemParams(BaseModel):
    """GET /admin/params response."""

    params: dict[str, str]
