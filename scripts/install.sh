#!/usr/bin/env bash
# Production install for Core Accounting.
#
# From a clone (Docker + Compose v2 already installed):
#   ./scripts/install.sh
#
# On a machine that does not have the repo yet:
#   curl -fsSL https://raw.githubusercontent.com/EricRenForCode/core-accounting/master/scripts/install.sh | bash
#
# Re-running keeps existing secrets. To set keys without editing the file:
#   DEEPSEEK_API_KEY=sk-... ./scripts/install.sh
#   PUBLIC_URL=https://accounting.example.com ./scripts/install.sh
#
# --write-env-only   create .env if missing, then exit (no Docker).

set -euo pipefail

REPO_URL="${REPO_URL:-https://github.com/EricRenForCode/core-accounting.git}"
REPO_DIR="${REPO_DIR:-core-accounting}"
WRITE_ENV_ONLY=0

if [[ "${1:-}" == "--write-env-only" ]]; then
  WRITE_ENV_ONLY=1
elif [[ -n "${1:-}" ]]; then
  echo "Usage: $0 [--write-env-only]" >&2
  exit 1
fi

log() { printf '[install] %s\n' "$*"; }
die() { printf '[install] %s\n' "$*" >&2; exit 1; }

require_cmd() {
  command -v "$1" >/dev/null 2>&1 || die "Missing '$1'. $2"
}

locate_repo() {
  local source="${BASH_SOURCE[0]:-}"
  if [[ -n "$source" && -f "$source" ]]; then
    local root
    root="$(cd "$(dirname "$source")/.." && pwd)"
    if [[ -f "$root/docker-compose.prod.yml" ]]; then
      cd "$root"
      return 0
    fi
  fi
  if [[ -f docker-compose.prod.yml && -f scripts/install.sh ]]; then
    return 0
  fi
  return 1
}

generate_secret() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 32
  elif [[ -r /dev/urandom ]]; then
    od -An -N32 -tx1 /dev/urandom | tr -d ' \n'
  else
    die "Need openssl or /dev/urandom to generate secrets."
  fi
}

detect_public_url() {
  if [[ -n "${PUBLIC_URL:-}" ]]; then
    printf '%s' "$PUBLIC_URL"
    return
  fi
  local port="${NGINX_PORT:-80}"
  local ip=""
  if command -v hostname >/dev/null 2>&1; then
    ip="$(hostname -I 2>/dev/null | awk '{for (i=1;i<=NF;i++) if ($i !~ /^127\./ && $i !~ /:/) {print $i; exit}}' || true)"
  fi
  if [[ -z "$ip" ]] && command -v ip >/dev/null 2>&1; then
    ip="$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for (i=1;i<=NF;i++) if ($i=="src") {print $(i+1); exit}}' || true)"
  fi
  local host="${ip:-core-accounting.private}"
  if [[ "$port" == "80" ]]; then
    printf 'http://%s' "$host"
  else
    printf 'http://%s:%s' "$host" "$port"
  fi
}

reject_bad_origin() {
  local url="$1"
  case "$url" in
    *localhost*|*127.0.0.1*)
      die "PUBLIC_URL must not contain localhost or 127.0.0.1 — production startup rejects it. Use the address users open, for example http://10.0.0.8 or https://accounting.example.com."
      ;;
    *\"*|*\'*)
      die "PUBLIC_URL must not contain quotes."
      ;;
  esac
}

read_env() {
  local key="$1"
  local line
  line="$(grep -E "^${key}=" "$ENV_FILE" | tail -n 1 || true)"
  printf '%s' "${line#"${key}="}"
}

upsert_env() {
  local key="$1"
  local value="$2"
  local tmp found=0
  tmp="$(mktemp)"
  while IFS= read -r line || [[ -n "$line" ]]; do
    if [[ "$line" == "$key="* ]]; then
      printf '%s=%s\n' "$key" "$value" >> "$tmp"
      found=1
    else
      printf '%s\n' "$line" >> "$tmp"
    fi
  done < "$ENV_FILE"
  if [[ "$found" == "0" ]]; then
    printf '%s=%s\n' "$key" "$value" >> "$tmp"
  fi
  mv "$tmp" "$ENV_FILE"
  chmod 600 "$ENV_FILE"
}

write_env() {
  local public_url="$1"
  local db_password db_ro_password jwt_secret admin_password
  db_password="$(generate_secret)"
  db_ro_password="$(generate_secret)"
  jwt_secret="$(generate_secret)"
  admin_password="$(generate_secret)"
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by scripts/install.sh. Do not commit this file.
DB_USER=${DB_USER:-accounting}
DB_PASSWORD=${db_password}
DB_NAME=${DB_NAME:-core_accounting}
DB_RO_USER=${DB_RO_USER:-accounting_ro}
DB_RO_PASSWORD=${db_ro_password}

NGINX_PORT=${NGINX_PORT:-80}
BACKEND_PORT=${BACKEND_PORT:-8000}

PUBLIC_URL=${public_url}
CORS_ORIGINS=["${public_url}"]

JWT_SECRET=${jwt_secret}
JWT_ALGORITHM=HS256
ACCESS_TOKEN_EXPIRE_MINUTES=120
REFRESH_TOKEN_EXPIRE_DAYS=1

INITIAL_ADMIN_PASSWORD=${admin_password}

DEEPSEEK_API_KEY=${DEEPSEEK_API_KEY:-sk-CHANGE_ME}
DEEPSEEK_MODEL=${DEEPSEEK_MODEL:-deepseek-chat}
DEEPSEEK_FALLBACK_MODEL=${DEEPSEEK_FALLBACK_MODEL:-deepseek-chat}

ALIYUN_OCR_ACCESS_KEY_ID=${ALIYUN_OCR_ACCESS_KEY_ID:-}
ALIYUN_OCR_ACCESS_KEY_SECRET=${ALIYUN_OCR_ACCESS_KEY_SECRET:-}
ALIYUN_OCR_ENDPOINT=${ALIYUN_OCR_ENDPOINT:-ocr-api.cn-hangzhou.aliyuncs.com}

DB_POOL_SIZE=20
DB_MAX_OVERFLOW=10
DB_POOL_TIMEOUT=30
DB_POOL_RECYCLE=3600

RATE_LIMIT_GLOBAL=60/minute
RATE_LIMIT_AI=10/minute
RATE_LIMIT_AUTH=5/minute

APP_NAME=Core Accounting
APP_VERSION=0.1.0

SYSTEM_USER_ID=00000000-0000-0000-0000-000000000000
EOF
  chmod 600 "$ENV_FILE"
  printf '%s\n' "$admin_password"
}

require_env_keys() {
  local key
  for key in DB_USER DB_PASSWORD DB_NAME DB_RO_USER DB_RO_PASSWORD NGINX_PORT BACKEND_PORT PUBLIC_URL CORS_ORIGINS JWT_SECRET INITIAL_ADMIN_PASSWORD; do
    if [[ -z "$(read_env "$key")" ]]; then
      die ".env is missing ${key}. See .env.example, or move .env aside and re-run to generate a new file."
    fi
  done
  local jwt dbpw public cors
  jwt="$(read_env JWT_SECRET)"
  dbpw="$(read_env DB_PASSWORD)"
  public="$(read_env PUBLIC_URL)"
  cors="$(read_env CORS_ORIGINS)"
  if [[ "$jwt" == "CHANGE_ME_IN_PRODUCTION_USE_A_STRONG_SECRET" || ${#jwt} -lt 32 ]]; then
    die "JWT_SECRET in .env is still a placeholder or shorter than 32 characters. Generate one with: openssl rand -hex 32"
  fi
  if [[ "$dbpw" == *CHANGE_ME* ]]; then
    die "DB_PASSWORD in .env is still a placeholder. Generate one with: openssl rand -hex 32"
  fi
  if [[ "$(read_env DB_RO_PASSWORD)" == *CHANGE_ME* ]]; then
    die "DB_RO_PASSWORD in .env is still a placeholder. Generate one with: openssl rand -hex 32"
  fi
  case "${public}${cors}" in
    *localhost*|*127.0.0.1*)
      die "PUBLIC_URL / CORS_ORIGINS must not contain localhost or 127.0.0.1."
      ;;
  esac
}

browser_url() {
  local public="$1"
  local port="$2"
  case "$public" in
    http://core-accounting.private|http://core-accounting.private:*)
      if [[ "$port" == "80" ]]; then
        printf 'http://127.0.0.1'
      else
        printf 'http://127.0.0.1:%s' "$port"
      fi
      ;;
    *)
      printf '%s' "$public"
      ;;
  esac
}

if ! locate_repo; then
  require_cmd git "Install Git, or clone the repo yourself and run ./scripts/install.sh."
  if [[ -e "$REPO_DIR" ]]; then
    die "Refusing to clone: ${REPO_DIR} already exists and is not a Core Accounting checkout."
  fi
  log "Cloning ${REPO_URL}"
  GIT_TERMINAL_PROMPT=0 git clone "$REPO_URL" "$REPO_DIR"
  cd "$REPO_DIR"
  exec ./scripts/install.sh "$@"
fi

ROOT="$(pwd)"
ENV_FILE="${ENV_FILE:-$ROOT/.env}"
COMPOSE=(docker compose -f "$ROOT/docker-compose.prod.yml")

if [[ "$WRITE_ENV_ONLY" == "0" ]]; then
  require_cmd docker "Install Docker Engine, then re-run this script."
  docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is required (the 'docker compose' command)."
  if ! docker info >/dev/null 2>&1; then
    die "Docker is installed but this user cannot talk to the daemon. Join the docker group, or re-run with sudo."
  fi
fi

if [[ -n "${NGINX_PORT:-}" && ! "$NGINX_PORT" =~ ^[0-9]+$ ]]; then
  die "NGINX_PORT must be a number."
fi
if [[ -n "${BACKEND_PORT:-}" && ! "$BACKEND_PORT" =~ ^[0-9]+$ ]]; then
  die "BACKEND_PORT must be a number."
fi

CREATED=0
ADMIN_PASSWORD=""
if [[ ! -f "$ENV_FILE" ]]; then
  public_url="$(detect_public_url)"
  reject_bad_origin "$public_url"
  log "Creating ${ENV_FILE}"
  ADMIN_PASSWORD="$(write_env "$public_url")"
  CREATED=1
else
  log "Using existing ${ENV_FILE} (secrets kept)"
  if [[ -n "${PUBLIC_URL:-}" ]]; then
    reject_bad_origin "$PUBLIC_URL"
    upsert_env PUBLIC_URL "$PUBLIC_URL"
    upsert_env CORS_ORIGINS "[\"${PUBLIC_URL}\"]"
    log "Updated PUBLIC_URL"
  fi
  if [[ -n "${DEEPSEEK_API_KEY:-}" ]]; then
    upsert_env DEEPSEEK_API_KEY "$DEEPSEEK_API_KEY"
    log "Updated DEEPSEEK_API_KEY"
  fi
  if [[ -n "${ALIYUN_OCR_ACCESS_KEY_ID:-}" ]]; then
    upsert_env ALIYUN_OCR_ACCESS_KEY_ID "$ALIYUN_OCR_ACCESS_KEY_ID"
    log "Updated ALIYUN_OCR_ACCESS_KEY_ID"
  fi
  if [[ -n "${ALIYUN_OCR_ACCESS_KEY_SECRET:-}" ]]; then
    upsert_env ALIYUN_OCR_ACCESS_KEY_SECRET "$ALIYUN_OCR_ACCESS_KEY_SECRET"
    log "Updated ALIYUN_OCR_ACCESS_KEY_SECRET"
  fi
  if [[ -n "${NGINX_PORT:-}" ]]; then
    upsert_env NGINX_PORT "$NGINX_PORT"
  fi
  if [[ -n "${BACKEND_PORT:-}" ]]; then
    upsert_env BACKEND_PORT "$BACKEND_PORT"
  fi
fi

require_env_keys

if [[ "$WRITE_ENV_ONLY" == "1" ]]; then
  log "Wrote ${ENV_FILE} only."
  exit 0
fi

log "Docker Compose $(docker compose version --short 2>/dev/null || docker compose version)"
log "Building and starting the production stack (first run downloads images and builds the app)"

help="$("${COMPOSE[@]}" up --help 2>&1 || true)"
set +e
if grep -q -- '--wait-timeout' <<<"$help"; then
  "${COMPOSE[@]}" up -d --build --wait --wait-timeout 600
  up_status=$?
elif grep -q -- '--wait' <<<"$help"; then
  "${COMPOSE[@]}" up -d --build --wait
  up_status=$?
else
  "${COMPOSE[@]}" up -d --build
  up_status=$?
fi
set -e

if [[ "$up_status" -ne 0 ]]; then
  echo "[install] The stack did not become healthy. Recent logs:" >&2
  "${COMPOSE[@]}" logs --tail 120 >&2 || true
  if [[ "$CREATED" == "1" ]]; then
    echo "[install] Generated secrets were kept in ${ENV_FILE}. The first-login password is INITIAL_ADMIN_PASSWORD." >&2
  fi
  exit "$up_status"
fi

PUBLIC="$(read_env PUBLIC_URL)"
NGINX="$(read_env NGINX_PORT)"
UI="$(browser_url "$PUBLIC" "$NGINX")"

cat <<EOF

Core Accounting is up.

  Web UI:   ${UI}
  Health:   ${UI}/api/v1/health
  API docs: ${UI}/docs

EOF

if [[ "$UI" != "$PUBLIC" ]]; then
  cat <<EOF
  No LAN address was detected, so startup recorded PUBLIC_URL=${PUBLIC}.
  Open the Web UI above on this machine. Same-origin requests do not need that name to resolve.
  For a domain or another host, re-run with PUBLIC_URL=https://your.domain ./scripts/install.sh

EOF
fi

if [[ "$CREATED" == "1" ]]; then
  cat <<EOF
  First login:  admin
  Password:     ${ADMIN_PASSWORD}
  Saved as INITIAL_ADMIN_PASSWORD in .env (mode 600).
  Change this password after you sign in. Later installs do not reset it.

EOF
fi

cat <<EOF
AI and OCR are optional. The app runs without them; those features stay unavailable until keys are set.

  DeepSeek:  DEEPSEEK_API_KEY=sk-... ./scripts/install.sh
  Aliyun OCR: ALIYUN_OCR_ACCESS_KEY_ID=... ALIYUN_OCR_ACCESS_KEY_SECRET=... ./scripts/install.sh
  Or edit .env and re-run ./scripts/install.sh

  Stop:     docker compose -f docker-compose.prod.yml stop
  Start:    docker compose -f docker-compose.prod.yml start
  Update:   git pull && ./scripts/install.sh
  Backup:   ./backups/backup.sh
  Logs:     docker compose -f docker-compose.prod.yml logs -f

Data lives in this Compose project's named Docker volumes. Keep the same checkout directory and COMPOSE_PROJECT_NAME when updating. 'stop' and 'down' keep volumes; 'down -v' deletes them.

This stack speaks HTTP. Terminate TLS in a proxy in front of Nginx and set PUBLIC_URL to the https origin.
EOF
